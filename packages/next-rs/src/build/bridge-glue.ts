/**
 * Generates the `#[napi]` and `wasm-bindgen` attribute glue (spec §82 steps 10
 * and 11, §89).
 *
 * `next-rs-runtime-napi` and `next-rs-runtime-wasm` own everything that has to be
 * *decided* — dispatch, JSON marshalling, the error envelope, the client-only
 * invariant. What they cannot own is the attribute macros themselves: `#[napi]`
 * pulls in a Node addon toolchain and `#[wasm_bindgen]` only makes sense on
 * `wasm32`, so putting either in a library crate would make the whole workspace
 * unbuildable on the other target.
 *
 * So the attributes are generated here, into a crate the application compiles for
 * exactly the target that needs it. The generated code is a thin, typed wrapper
 * per export over `NapiBridge::call_json` / `WasmBridge::call_json`.
 */

import type { ExportTarget, RustExport } from './rust-exports'
import { rustTypeToTypeScript, toCamelCase } from './rust-exports'

export interface BridgeGlueOptions {
  /**
   * The crate the application's `#[export]` functions live in, as named in
   * `Cargo.toml` with `-` replaced by `_`. Generated glue calls
   * `<crate>::<module>::__next_rs_export_<name>()` to build the registry.
   */
  appCrate: string
  /**
   * The crate the *browser* bundle depends on. Defaults to `appCrate`.
   *
   * These differ whenever the application crate is a server: a crate that
   * depends on tokio's filesystem or networking does not compile for
   * `wasm32-unknown-unknown`, so `#[export(client)]` functions have to live
   * somewhere that does. Pointing the WASM bundle at that crate rather than at
   * the whole application is the crate-level reading of §11.
   */
  wasmCrate?: string
  buildId: string
}

/** One generated file: its path under `.next-rs/generated/` and its contents. */
export interface GeneratedGlue {
  path: string
  contents: string
}

/** Raised when an export cannot be given attribute glue. */
export class BridgeGlueError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'BridgeGlueError'
  }
}

const HEADER = [
  '// Generated by `next-rs build`. Do not edit.',
  '//',
  '// Regenerate with `next-rs build`; this file is derived from the `#[export]`',
  '// attributes in the application crate.',
]

/**
 * Generates `.next-rs/generated/napi.rs` (spec §82 step 10).
 *
 * Every export gets its own `#[napi]` function so Node sees real names and real
 * arity, rather than one stringly-typed `call(name, args)` entry point. The
 * argument and return marshalling still goes through the bridge, so the decisions
 * stay in Rust and stay tested.
 */
export function generateNapiGlue(
  exports: RustExport[],
  options: BridgeGlueOptions
): string {
  const sorted = sortExports(exports)
  const registrations = sorted.map(
    (rustExport) =>
      `            registry.register(${registrationPath(rustExport, options)})?;`
  )

  const functions = sorted.map((rustExport) =>
    napiFunction(rustExport).join('\n')
  )

  return [
    ...HEADER,
    '//',
    '// `#[napi]` glue: the Node compatibility path (spec §3.1, §89).',
    '',
    '#![allow(clippy::needless_pass_by_value, clippy::unused_async)]',
    '',
    'use napi_derive::napi;',
    'use next_rs::__private::core::ExportRegistry;',
    'use next_rs_runtime_napi::NapiBridge;',
    'use std::sync::{Arc, OnceLock};',
    '',
    `pub const BUILD_ID: &str = ${JSON.stringify(options.buildId)};`,
    '',
    'static BRIDGE: OnceLock<NapiBridge> = OnceLock::new();',
    '',
    '/// Builds the bridge once, over the registry this build scanned.',
    "fn bridge() -> &'static NapiBridge {",
    '    BRIDGE.get_or_init(|| {',
    '        let build = || -> next_rs::Result<ExportRegistry> {',
    '            let mut registry = ExportRegistry::new();',
    ...(registrations.length > 0
      ? registrations
      : ['            // no exports']),
    '            Ok(registry)',
    '        };',
    '        // A registry that cannot be built is a build bug, not a request',
    '        // failure: fail at load rather than on the first call.',
    '        NapiBridge::new(Arc::new(build().expect("next-rs: export registry")))',
    '    })',
    '}',
    '',
    '/// Names Node may call, so a stale binding is caught at start-up.',
    '#[napi]',
    'pub fn next_rs_export_names() -> Vec<String> {',
    '    bridge().descriptors().into_iter().map(|d| d.js_name).collect()',
    '}',
    '',
    '/// The build this addon was generated for (spec §66).',
    '#[napi]',
    'pub fn next_rs_build_id() -> String {',
    '    BUILD_ID.to_owned()',
    '}',
    '',
    ...functions,
  ].join('\n')
}

/**
 * Generates `.next-rs/generated/wasm.rs` (spec §82 step 11, §10, §11).
 *
 * Only `#[export(client)]` functions appear. A server-only export reaching this
 * file would be a build bug; `WasmBridge::strict` is the runtime backstop for the
 * same invariant.
 */
export function generateWasmGlue(
  exports: RustExport[],
  options: BridgeGlueOptions
): string {
  const clientExports = sortExports(
    exports.filter((rustExport) => rustExport.target === 'client')
  )
  const wasmOptions = {
    ...options,
    appCrate: options.wasmCrate ?? options.appCrate,
  }
  const registrations = clientExports.map(
    (rustExport) =>
      `            registry.register(${registrationPath(rustExport, wasmOptions)})?;`
  )
  const functions = clientExports.map((rustExport) =>
    wasmFunction(rustExport).join('\n')
  )

  return [
    ...HEADER,
    '//',
    '// `wasm-bindgen` glue: browser-compatible exports only (spec §10, §11).',
    '',
    '#![allow(clippy::unused_async)]',
    '',
    'use next_rs::__private::core::ExportRegistry;',
    'use next_rs_runtime_wasm::WasmBridge;',
    'use std::sync::OnceLock;',
    'use wasm_bindgen::prelude::*;',
    '',
    `pub const BUILD_ID: &str = ${JSON.stringify(options.buildId)};`,
    '',
    'static BRIDGE: OnceLock<WasmBridge> = OnceLock::new();',
    '',
    "fn bridge() -> &'static WasmBridge {",
    '    BRIDGE.get_or_init(|| {',
    '        let build = || -> next_rs::Result<ExportRegistry> {',
    '            let mut registry = ExportRegistry::new();',
    ...(registrations.length > 0
      ? registrations
      : ['            // no client exports']),
    '            Ok(registry)',
    '        };',
    '        let registry = build().expect("next-rs: client export registry");',
    '        // `strict` refuses a server-only export even if one reached the',
    '        // bundle: build-time checking catches the import, this catches a',
    '        // mis-generated bundle (spec §11).',
    '        WasmBridge::strict(&registry).expect("next-rs: server-only export in the browser bundle")',
    '    })',
    '}',
    '',
    '/// Names the browser may call.',
    '#[wasm_bindgen(js_name = nextRsExportNames)]',
    'pub fn next_rs_export_names() -> Vec<String> {',
    '    bridge().names()',
    '}',
    '',
    '#[wasm_bindgen(js_name = nextRsBuildId)]',
    'pub fn next_rs_build_id() -> String {',
    '    BUILD_ID.to_owned()',
    '}',
    '',
    ...functions,
    WASM_HELPERS,
  ].join('\n')
}

/**
 * Generates the `Cargo.toml` for the N-API addon crate.
 *
 * A separate crate, not a feature on `next-rs-runtime-napi`: `cdylib` and the
 * `napi` build dependencies are toolchain-specific, and keeping them out of the
 * library crate is what lets `cargo test --workspace` run anywhere.
 */
export function generateNapiCargoToml(options: {
  appCrate: string
  appCratePath: string
  nextRsPath: string
}): string {
  return `${[
    '# Generated by `next-rs build`. Do not edit.',
    '[package]',
    'name = "next-rs-napi-addon"',
    'version = "0.0.0"',
    'edition = "2021"',
    'publish = false',
    '',
    '[lib]',
    'crate-type = ["cdylib"]',
    'path = "napi.rs"',
    '',
    '[dependencies]',
    `${options.appCrate.replace(/_/g, '-')} = { path = ${JSON.stringify(options.appCratePath)} }`,
    `next-rs = { path = ${JSON.stringify(options.nextRsPath)} }`,
    `next-rs-runtime-napi = { path = ${JSON.stringify(
      `${options.nextRsPath}/../next-rs-runtime-napi`
    )} }`,
    'napi = { version = "2", default-features = false, features = ["napi4", "async", "serde-json"] }',
    'napi-derive = "2"',
    'serde_json = "1"',
    '',
    '[build-dependencies]',
    'napi-build = "2"',
  ].join('\n')}\n`
}

/** Generates the `Cargo.toml` for the browser WASM crate. */
export function generateWasmCargoToml(options: {
  appCrate: string
  appCratePath: string
  nextRsPath: string
  /** Defaults to `appCrate`; see [`BridgeGlueOptions.wasmCrate`]. */
  wasmCrate?: string
  wasmCratePath?: string
}): string {
  const crate = options.wasmCrate ?? options.appCrate
  const cratePath = options.wasmCratePath ?? options.appCratePath
  return `${[
    '# Generated by `next-rs build`. Do not edit.',
    '[package]',
    'name = "next-rs-wasm-exports"',
    'version = "0.0.0"',
    'edition = "2021"',
    'publish = false',
    '',
    '[lib]',
    'crate-type = ["cdylib", "rlib"]',
    'path = "wasm.rs"',
    '',
    '[dependencies]',
    `${crate.replace(/_/g, '-')} = { path = ${JSON.stringify(cratePath)} }`,
    `next-rs = { path = ${JSON.stringify(options.nextRsPath)} }`,
    `next-rs-runtime-wasm = { path = ${JSON.stringify(
      `${options.nextRsPath}/../next-rs-runtime-wasm`
    )} }`,
    'wasm-bindgen = "0.2"',
    'wasm-bindgen-futures = "0.4"',
    'serde-wasm-bindgen = "0.6"',
    'serde_json = "1"',
    '',
    '# `wasm32-unknown-unknown` has no OS entropy source, so `getrandom` refuses',
    "# to build for it unless told to use the browser's `crypto`. The dependency",
    '# arrives through the application crate, so the feature has to be enabled',
    '# here rather than there.',
    'getrandom = { version = "0.2", features = ["js"] }',
  ].join('\n')}\n`
}

/** `build.rs` for the N-API addon; `napi-build` emits the linker flags. */
export const NAPI_BUILD_RS = `${[
  '// Generated by `next-rs build`. Do not edit.',
  'fn main() {',
  '    napi_build::setup();',
  '}',
].join('\n')}\n`

/**
 * The `.d.ts` for the generated N-API addon.
 *
 * `.next-rs/generated/rust.d.ts` describes the *application-facing* API; this
 * describes the addon surface the loader module sits on top of.
 */
export function generateNapiDeclarations(exports: RustExport[]): string {
  const lines = [
    '// Generated by `next-rs build`. Do not edit.',
    '//',
    '// The N-API addon surface. Applications import `@app/rust`, not this.',
    '',
    'export function nextRsExportNames(): string[]',
    'export function nextRsBuildId(): string',
    '',
  ]
  for (const rustExport of sortExports(exports)) {
    const parameters = rustExport.parameters
      .map(
        (parameter) =>
          `${toCamelCase(parameter.name)}: ${rustTypeToTypeScript(parameter.type)}`
      )
      .join(', ')
    lines.push(
      `export function ${rustExport.jsName}(${parameters}): Promise<${returnTypeScript(
        rustExport
      )}>`
    )
  }
  lines.push('')
  return lines.join('\n')
}

/**
 * The loader module applications' `@app/rust` alias points at (spec §7).
 *
 * It picks the N-API addon on the server and the WASM bundle in the browser, so
 * a `#[export(client)]` function is the same import on both sides.
 */
export function generateRustAliasModule(exports: RustExport[]): string {
  const client = sortExports(
    exports.filter((rustExport) => rustExport.target === 'client')
  )
  const server = sortExports(
    exports.filter((rustExport) => rustExport.target !== 'client')
  )

  return `${[
    '// Generated by `next-rs build`. Do not edit.',
    '//',
    '// The module `@app/rust` resolves to. Server-only exports throw in the',
    '// browser rather than silently returning undefined; the build already fails',
    '// on such an import (spec §11), so reaching this is a bundler bug.',
    '',
    "const isServer = typeof window === 'undefined'",
    '',
    'let addon',
    'function server() {',
    '  if (!addon) {',
    "    addon = require('./napi.node')",
    '  }',
    '  return addon',
    '}',
    '',
    'let wasm',
    'export async function __initWasm(init) {',
    '  wasm = await init()',
    '  return wasm',
    '}',
    '',
    'function client() {',
    '  if (!wasm) {',
    '    throw new Error(',
    "      'next-rs: the browser WASM bundle is not initialised; await __initWasm() first'",
    '    )',
    '  }',
    '  return wasm',
    '}',
    '',
    ...client.flatMap((rustExport) => [
      `export function ${rustExport.jsName}(...args) {`,
      `  return (isServer ? server() : client()).${rustExport.jsName}(...args)`,
      '}',
      '',
    ]),
    ...server.flatMap((rustExport) => [
      `export function ${rustExport.jsName}(...args) {`,
      '  if (!isServer) {',
      `    throw new Error('next-rs: ${rustExport.jsName} is server-only (spec §11)')`,
      '  }',
      `  return server().${rustExport.jsName}(...args)`,
      '}',
      '',
    ]),
  ].join('\n')}`
}

/** Every generated bridge file, for a build that needs both targets. */
export function generateBridgeGlue(
  exports: RustExport[],
  options: BridgeGlueOptions & {
    appCratePath: string
    nextRsPath: string
    /** Path to the browser-safe crate; defaults to `appCratePath`. */
    wasmCratePath?: string
    /** Emit the WASM crate. False when no `#[export(client)]` exists (spec §10). */
    wasm: boolean
    /** Emit the N-API crate. */
    napi: boolean
  }
): GeneratedGlue[] {
  assertGlueable(exports)
  const files: GeneratedGlue[] = []

  if (options.napi) {
    files.push(
      {
        path: 'generated/napi.rs',
        contents: `${generateNapiGlue(exports, options)}\n`,
      },
      {
        path: 'generated/napi.Cargo.toml',
        contents: generateNapiCargoToml(options),
      },
      { path: 'generated/napi.build.rs', contents: NAPI_BUILD_RS },
      {
        path: 'generated/napi.d.ts',
        contents: generateNapiDeclarations(exports),
      }
    )
  }

  if (options.wasm) {
    files.push(
      {
        path: 'generated/wasm.rs',
        contents: `${generateWasmGlue(exports, options)}\n`,
      },
      {
        path: 'generated/wasm.Cargo.toml',
        contents: generateWasmCargoToml(options),
      }
    )
  }

  if (options.napi || options.wasm) {
    files.push({
      path: 'generated/rust.js',
      contents: generateRustAliasModule(exports),
    })
  }

  return files
}

/**
 * Rejects exports the glue cannot express.
 *
 * Every argument crosses as JSON, so the constraint is not "which Rust types" but
 * "which *names*": a Rust parameter called `type` or `await` cannot appear in the
 * generated JavaScript signature. Failing here beats emitting a file that will
 * not compile.
 */
export function assertGlueable(exports: RustExport[]): void {
  const reserved = new Set([
    'await',
    'break',
    'case',
    'catch',
    'class',
    'const',
    'continue',
    'debugger',
    'default',
    'delete',
    'do',
    'else',
    'enum',
    'export',
    'extends',
    'finally',
    'for',
    'function',
    'if',
    'import',
    'in',
    'instanceof',
    'new',
    'return',
    'super',
    'switch',
    'this',
    'throw',
    'try',
    'typeof',
    'var',
    'void',
    'while',
    'with',
    'yield',
  ])

  for (const rustExport of exports) {
    for (const parameter of rustExport.parameters) {
      const jsName = toCamelCase(parameter.name)
      if (reserved.has(jsName)) {
        throw new BridgeGlueError(
          `\`${rustExport.name}\` has a parameter named \`${parameter.name}\`, which is a ` +
            'JavaScript reserved word; rename it so bindings can be generated'
        )
      }
    }
  }
}

/**
 * One `#[napi]` wrapper.
 *
 * Arguments arrive as `serde_json::Value` so the bridge stays the only decoder,
 * and the wrapper is always `async fn`: N-API turns that into a Promise, which is
 * what a fallible export needs even when the Rust function is synchronous.
 */
function napiFunction(rustExport: RustExport): string[] {
  const parameters = rustExport.parameters
    .map((parameter) => `${jsSafe(parameter.name)}: serde_json::Value`)
    .join(', ')
  const argumentList = rustExport.parameters
    .map((parameter) => jsSafe(parameter.name))
    .join(', ')

  return [
    `/// \`${rustExport.name}\`, imported from TypeScript as \`${rustExport.jsName}\`.`,
    `#[napi(js_name = ${JSON.stringify(rustExport.jsName)})]`,
    `pub async fn ${rustExport.name}(${parameters}) -> napi::Result<serde_json::Value> {`,
    `    let args = vec![${argumentList}];`,
    `    let payload = serde_json::Value::Array(args).to_string();`,
    `    match bridge().call(${JSON.stringify(rustExport.name)}, &payload).await {`,
    '        Ok(value) => Ok(value),',
    // A Rust error becomes a rejected Promise carrying the redacted public
    // message and the stable code, never the internal detail (spec §69).
    '        Err(error) => Err(napi::Error::new(',
    '            napi::Status::GenericFailure,',
    '            format!("{}: {}", error.code(), error.public_message()),',
    '        )),',
    '    }',
    '}',
    '',
  ]
}

/** One `wasm-bindgen` wrapper. */
function wasmFunction(rustExport: RustExport): string[] {
  const parameters = rustExport.parameters
    .map((parameter) => `${jsSafe(parameter.name)}: JsValue`)
    .join(', ')
  const conversions = rustExport.parameters.map(
    (parameter) =>
      `    let ${jsSafe(parameter.name)} = js_to_json(${jsSafe(parameter.name)}, ${JSON.stringify(
        parameter.name
      )})?;`
  )
  const argumentList = rustExport.parameters
    .map((parameter) => jsSafe(parameter.name))
    .join(', ')

  return [
    `/// \`${rustExport.name}\`, called from the browser as \`${rustExport.jsName}\`.`,
    `#[wasm_bindgen(js_name = ${JSON.stringify(rustExport.jsName)})]`,
    `pub async fn ${rustExport.name}(${parameters}) -> Result<JsValue, JsValue> {`,
    ...conversions,
    `    let args = serde_json::Value::Array(vec![${argumentList}]).to_string();`,
    `    let envelope = bridge().call_json(${JSON.stringify(rustExport.name)}, &args).await;`,
    '    unwrap_envelope(&envelope)',
    '}',
    '',
  ]
}

/** Shared helpers appended to the WASM glue. */
export const WASM_HELPERS = [
  '/// Converts one JavaScript argument to JSON, naming the parameter on failure.',
  'fn js_to_json(value: JsValue, name: &str) -> Result<serde_json::Value, JsValue> {',
  '    serde_wasm_bindgen::from_value(value)',
  '        .map_err(|error| JsValue::from_str(&format!("argument `{name}`: {error}")))',
  '}',
  '',
  '/// Turns the bridge envelope into a resolved or rejected promise value.',
  'fn unwrap_envelope(envelope: &str) -> Result<JsValue, JsValue> {',
  '    let parsed: serde_json::Value = serde_json::from_str(envelope)',
  '        .map_err(|error| JsValue::from_str(&format!("next-rs: bad envelope: {error}")))?;',
  '    if let Some(error) = parsed.get("error") {',
  '        let code = error.get("code").and_then(|v| v.as_str()).unwrap_or("INTERNAL");',
  '        let message = error.get("message").and_then(|v| v.as_str()).unwrap_or("failed");',
  '        return Err(JsValue::from_str(&format!("{code}: {message}")));',
  '    }',
  '    let ok = parsed.get("ok").cloned().unwrap_or(serde_json::Value::Null);',
  '    serde_wasm_bindgen::to_value(&ok)',
  '        .map_err(|error| JsValue::from_str(&format!("next-rs: bad result: {error}")))',
  '}',
  '',
].join('\n')

/**
 * The full Rust path to an export's registration function.
 *
 * The registration is generated by `#[export]` *next to the function*, so it
 * lives in that function's module — and the glue is a different crate, which
 * has to name the whole path. When the module could not be worked out, this
 * fails with the file name rather than emitting a path that will not compile:
 * a build error naming the file beats a `cannot find function in crate` from
 * rustc pointing at generated code.
 */
function registrationPath(
  rustExport: RustExport,
  options: BridgeGlueOptions
): string {
  if (rustExport.modulePath === undefined) {
    throw new BridgeGlueError(
      `\`${rustExport.name}\`${
        rustExport.sourcePath ? ` in ${rustExport.sourcePath}` : ''
      } is outside the application crate's source root, so next-rs cannot work ` +
        'out its Rust module path. Move the `#[export]` into the crate source ' +
        'tree, or set `crateSrcDir` to the root it lives under.'
    )
  }
  const module = rustExport.modulePath
    ? `${options.appCrate}::${rustExport.modulePath}`
    : options.appCrate
  return `${module}::__next_rs_export_${rustExport.name}()`
}

function returnTypeScript(rustExport: RustExport): string {
  return rustExport.returnType
    ? rustTypeToTypeScript(rustExport.returnType)
    : 'void'
}

/** Rust parameter names may collide with Rust keywords once re-emitted. */
function jsSafe(name: string): string {
  const keywords = new Set([
    'as',
    'break',
    'const',
    'continue',
    'crate',
    'else',
    'enum',
    'extern',
    'false',
    'fn',
    'for',
    'if',
    'impl',
    'in',
    'let',
    'loop',
    'match',
    'mod',
    'move',
    'mut',
    'pub',
    'ref',
    'return',
    'self',
    'static',
    'struct',
    'super',
    'trait',
    'true',
    'type',
    'unsafe',
    'use',
    'where',
    'while',
    'async',
    'await',
    'dyn',
  ])
  return keywords.has(name) ? `r#${name}` : name
}

function sortExports(exports: RustExport[]): RustExport[] {
  return [...exports].sort((left, right) => (left.name < right.name ? -1 : 1))
}

/** True when this build needs the browser WASM toolchain at all (spec §10). */
export function needsWasm(exports: { target: ExportTarget }[]): boolean {
  return exports.some((rustExport) => rustExport.target === 'client')
}
