/**
 * Code generation: turns the Rust build manifest into TypeScript the app
 * imports.
 *
 * Three outputs:
 *
 * - `types.d.ts` — the boundary types, emitted from the Rust IDL.
 * - `islands.ts` — a `ServerIsland` descriptor per `#[next::island]`, typed with
 *   that island's props and its declared slots. This is what makes
 *   `<Island of={Chart}>` type-check, and what lets the build reject a slot fill
 *   whose props do not match.
 * - `routes.ts` — the Rust route table, merged with `route.ts` files and checked
 *   for collisions.
 */

import fs from 'node:fs'
import path from 'node:path'

export interface IslandManifestEntry {
  id: string
  props_ts: string
  slots: Array<{ name: string; props_ts: string }>
}

export interface RouteManifestEntry {
  path: string
  method: string
}

export interface Manifest {
  islands: IslandManifestEntry[]
  routes: RouteManifestEntry[]
  types: string
}

const HEADER = `// Generated by next:rust. Do not edit.\n// Regenerated on every build from the Rust workspace.\n\n`

function toPascalCase(id: string): string {
  return id
    .split(/[_\-\s]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('')
}

export function generateTypes(manifest: Manifest): string {
  return HEADER + (manifest.types || '// (no boundary types declared)\n')
}

/**
 * Emits one descriptor per island.
 *
 * The slot prop types are baked into the descriptor's type parameters, which is
 * what gives `<Island of={Chart}><Island of={Legend} slot="legend" /></Island>`
 * its checking: the author supplies `Omit<LegendProps, keyof RustSlotProps>` and
 * Rust supplies the rest.
 */
export function generateIslands(manifest: Manifest): string {
  const lines: string[] = [HEADER]
  lines.push(`import type { ServerIsland } from 'next/island'`)

  // Only bare identifiers are named declarations. A structural type like
  // `Record<string, never>` also starts with a capital and must not be
  // imported as if it were one.
  const isNamedType = (ts: string) => /^[A-Z][A-Za-z0-9_]*$/.test(ts)

  const typeNames = new Set<string>()
  for (const island of manifest.islands) {
    if (isNamedType(island.props_ts)) typeNames.add(island.props_ts)
    for (const slot of island.slots) {
      if (isNamedType(slot.props_ts)) typeNames.add(slot.props_ts)
    }
  }
  if (typeNames.size > 0) {
    lines.push(`import type { ${[...typeNames].sort().join(', ')} } from './types'`)
  }
  lines.push('')

  for (const island of manifest.islands) {
    const name = toPascalCase(island.id)
    const slotMap =
      island.slots.length === 0
        ? '{}'
        : `{\n${island.slots.map((s) => `  ${JSON.stringify(s.name)}: ${s.props_ts}`).join('\n')}\n}`

    lines.push(`/** Server island \`${island.id}\`, rendered by Rust. */`)
    lines.push(
      `export const ${name}: ServerIsland<${island.props_ts}, ${slotMap}> = {`,
      `  kind: 'server',`,
      `  id: ${JSON.stringify(island.id)},`,
      `  slots: ${JSON.stringify(island.slots.map((s) => s.name))},`,
      `}`,
      ''
    )
  }

  return lines.join('\n')
}

export function generateRoutes(manifest: Manifest): string {
  const lines: string[] = [HEADER]
  lines.push(`export const rustRoutes = ${JSON.stringify(manifest.routes, null, 2)} as const`)
  lines.push('')
  return lines.join('\n')
}

/**
 * A Rust handler and a TS handler claiming the same method+path is ambiguous,
 * and silently preferring one would be a debugging nightmare.
 */
export function assertNoRouteConflicts(
  rustRoutes: RouteManifestEntry[],
  tsRoutes: RouteManifestEntry[]
): void {
  const seen = new Map<string, string>()
  for (const r of tsRoutes) seen.set(`${r.method} ${r.path}`, 'route.ts')

  const conflicts: string[] = []
  for (const r of rustRoutes) {
    const key = `${r.method} ${r.path}`
    if (seen.has(key)) conflicts.push(`  ${key} is handled by both route.rs and ${seen.get(key)}`)
    seen.set(key, 'route.rs')
  }

  if (conflicts.length > 0) {
    throw new Error(`[next:rust] conflicting route handlers:\n${conflicts.join('\n')}`)
  }
}

/**
 * Validates `<Island>` usage against what Rust actually declared.
 *
 * Runs over the island usages the bundler collected. Three rules: every
 * declared slot is filled, every fill names a declared slot, and only islands
 * fill slots.
 */
export interface IslandUsage {
  file: string
  islandId: string
  filledSlots: string[]
}

export function validateIslandUsage(manifest: Manifest, usages: IslandUsage[]): string[] {
  const byId = new Map(manifest.islands.map((i) => [i.id, i]))
  const errors: string[] = []

  for (const usage of usages) {
    const island = byId.get(usage.islandId)
    if (!island) {
      errors.push(`${usage.file}: no Rust island named \`${usage.islandId}\``)
      continue
    }
    const declared = new Set(island.slots.map((s) => s.name))
    const filled = new Set(usage.filledSlots)

    for (const name of filled) {
      if (!declared.has(name)) {
        errors.push(
          `${usage.file}: island \`${usage.islandId}\` has no slot named \`${name}\`` +
            (declared.size ? ` (declared: ${[...declared].join(', ')})` : ' (it declares none)')
        )
      }
    }
    for (const name of declared) {
      if (!filled.has(name)) {
        errors.push(
          `${usage.file}: island \`${usage.islandId}\` declares slot \`${name}\` but nothing fills it`
        )
      }
    }
  }

  return errors
}

export function writeGenerated(dir: string, manifest: Manifest): void {
  fs.mkdirSync(dir, { recursive: true })
  const files: Array<[string, string]> = [
    ['types.d.ts', generateTypes(manifest)],
    ['islands.ts', generateIslands(manifest)],
    ['routes.ts', generateRoutes(manifest)],
  ]
  for (const [name, contents] of files) {
    const target = path.join(dir, name)
    // Only write when changed: a rewritten file invalidates the bundler's graph
    // even when the bytes are identical, which would defeat the no-op rebuild.
    const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null
    if (existing !== contents) fs.writeFileSync(target, contents)
  }
}
