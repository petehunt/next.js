/**
 * Generates the entry point for the React SSR renderer process (spec §79, §82
 * step 13).
 *
 * The renderer is a separate process by design: a page with no `.ssr()` slot must
 * never initialise, invoke or communicate with it (spec §80), and that guarantee
 * is much easier to hold — and to test — when it is a process boundary rather
 * than a module boundary.
 *
 * What is generated here is only the *wiring*: which components exist and where
 * to import them from. The rendering itself lives in `@next/rs/renderer`, so it
 * is ordinary tested code rather than a generated string.
 */

import type { RegisteredComponent } from './component-registry'

export interface RendererEntryOptions {
  buildId: string
  /**
   * Specifier for the renderer runtime. Defaults to the published package; a
   * monorepo build points it at the source.
   */
  runtimeSpecifier?: string
  /** Where the component map was generated, relative to the entry. */
  componentsSpecifier?: string
}

export const DEFAULT_RUNTIME_SPECIFIER = '@next/rs/renderer'

/**
 * The readiness handshake `next-rs-react-renderer` waits for on stdout.
 *
 * Assembled rather than written out so this file does not itself contain a
 * template placeholder that lint would read as an unescaped interpolation.
 */
const READY_LINE = ['`next-rs-renderer ready $', '{server.port}\\n`'].join('')

/**
 * Generates `.next-rs/generated/react-renderer.mjs`.
 *
 * ESM, because `react-dom/server` and the Client Components it renders are ESM,
 * and because dynamic `import()` is how a component is loaded lazily — a slot
 * that is never rendered should never load its module.
 */
export function generateRendererEntry(
  components: RegisteredComponent[],
  options: RendererEntryOptions
): string {
  const runtime = options.runtimeSpecifier ?? DEFAULT_RUNTIME_SPECIFIER
  const componentsModule = options.componentsSpecifier ?? './components.js'

  return `${[
    '// Generated by `next-rs build`. Do not edit.',
    '//',
    '// The React SSR renderer process (spec §79). Started by the Rust runtime only',
    '// when a build contains at least one `.ssr()`-capable slot; a client-only page',
    '// never reaches it (spec §80).',
    '',
    `import { startRendererServer } from ${JSON.stringify(runtime)}`,
    `import { loadComponent } from ${JSON.stringify(componentsModule)}`,
    '',
    `const BUILD_ID = ${JSON.stringify(options.buildId)}`,
    `const COMPONENT_IDS = ${JSON.stringify(
      [...components].map((component) => component.id).sort()
    )}`,
    '',
    'const port = Number(process.env.NEXT_RS_RENDERER_PORT ?? 0)',
    "const host = process.env.NEXT_RS_RENDERER_HOST ?? '127.0.0.1'",
    '',
    'const server = await startRendererServer({',
    '  buildId: BUILD_ID,',
    '  componentIds: COMPONENT_IDS,',
    '  loadComponent,',
    '  host,',
    '  port,',
    '})',
    '',
    '// The Rust side waits for this line before sending the first batch, so it',
    '// never has to poll or guess a port.',
    `process.stdout.write(${READY_LINE})`,
    '',
    'const shutdown = () => {',
    '  server.close().then(',
    '    () => process.exit(0),',
    '    () => process.exit(1)',
    '  )',
    '}',
    "process.on('SIGTERM', shutdown)",
    "process.on('SIGINT', shutdown)",
    '',
  ].join('\n')}`
}
